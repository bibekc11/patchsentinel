"""Outcome reporting, human approval (role-checked) and export of approved fixes."""
from __future__ import annotations
import json, subprocess
from pathlib import Path

DEFAULT_POLICY = {
    "scanners": ["bandit", "builtin"], "ignore_rules": ["B101", "B404"], "max_retries": 3,
    "approver_roles": ["reviewer", "admin"],
    # ASSUMPTIONS for the ROI estimate. Replace with your team's own figures; they are not measured results.
    "manual_fix_minutes": 60, "manual_triage_minutes": 15,
}
LABELS = {"verified": "Verified, awaiting human approval", "rejected_false_positive": "Rejected as false positive",
          "escalated": "Escalated to a human", "escalated_unreproducible": "Escalated: exploit not reproducible",
          "escalated_retries_exhausted": "Blocked: no safe fix within retry cap", "approved": "Approved by human", "declined": "Declined by human"}


def load_policy(path):
    pol = dict(DEFAULT_POLICY)
    if path:
        pol.update(json.loads(Path(path).read_text(encoding="utf-8")))
    return pol


def approve(results, mode, approver, role, policy, audit):
    """Nothing is applied without a human decision from an allowed role. mode: none | interactive | yes."""
    if mode == "none":
        return
    if role not in policy["approver_roles"]:
        audit.log("approval_refused", approver=approver, role=role, reason="role not permitted")
        raise SystemExit(f"role {role!r} may not approve fixes (allowed: {policy['approver_roles']})")
    for r in results:
        if r["status"] != "verified":
            continue
        a = r["alert"]
        if mode == "interactive":
            print(f"\n=== {a['id']} {a['rule_id']} {a['file']}:{a['function']}() ===\n{r['diff']}\n")
            ok = input("Approve this fix? [y/N] ").strip().lower() == "y"
        else:
            ok = True
        r["status"] = "approved" if ok else "declined"
        print(f"  {a['id']} -> {r['status']} by {approver} ({role})")
        audit.log("human_decision", alert=a["id"], approver=approver, role=role, decision=r["status"], mode=mode)


def export(results, repo: Path, out: Path, apply: bool, audit):
    for r in results:
        a = r["alert"]
        d = out / a["id"]
        d.mkdir(parents=True, exist_ok=True)
        if r.get("spec"):
            from .exploit import render_tests
            (d / "exploit_test.py").write_text(render_tests(r["spec"]), encoding="utf-8")
        if r["status"] in ("approved", "verified"):
            (d / "fix.patch").write_text(r["diff"] + "\n", encoding="utf-8")
            (d / "PR_BODY.md").write_text(pr_body(r), encoding="utf-8")
        if r["status"] == "approved" and apply:
            branch = f"patchsentinel/{a['id'].lower()}-{a['function']}"
            wt = out / f"_wt_{a['id']}"
            try:
                ident = [] if subprocess.run(["git", "-C", str(repo), "config", "user.name"], capture_output=True, text=True).stdout.strip() \
                    else ["-c", "user.name=PatchSentinel", "-c", "user.email=patchsentinel@localhost"]
                subprocess.run(["git", "-C", str(repo), "worktree", "add", "-q", "-b", branch, str(wt)], check=True, capture_output=True)
                (wt / a["file"]).write_text(r["new_source"], encoding="utf-8")
                subprocess.run(["git", "-C", str(wt), "add", a["file"]], check=True, capture_output=True)
                subprocess.run(["git", "-C", str(wt), *ident, "commit", "-q", "-m",
                                f"fix({a['function']}): {a['rule_id']} (PatchSentinel, human-approved)"], check=True, capture_output=True)
                audit.log("branch_created", alert=a["id"], branch=branch)
                r["branch"] = branch
            except subprocess.CalledProcessError as e:
                audit.log("branch_failed", alert=a["id"], error=(e.stderr or b"").decode()[:200])
            finally:
                subprocess.run(["git", "-C", str(repo), "worktree", "remove", "--force", str(wt)], capture_output=True)


def pr_body(r) -> str:
    a = r["alert"]
    rows = "\n".join(f"| {k} | {'PASS' if v[0] else 'FAIL'} | {v[1][:110]} |" for k, v in r["checks"].items())
    return (f"## Fix for {a['rule_id']} in `{a['file']}` `{a['function']}()`\n\n{r['triage']['reason']}\n\n"
            f"### Evidence (all produced by the deterministic verifier)\n| Check | Result | Detail |\n|---|---|---|\n{rows}\n\n"
            f"Independent reviewer: {r['review'].get('engine')}, approved after {r['attempt']} attempt(s).\n\n"
            "**Generated by PatchSentinel. A human must review and approve before merge.**\n")


def roi(results, policy, wall_seconds):
    c = lambda s: sum(1 for r in results if r["status"] in s)
    fixed = c(("verified", "approved", "declined"))
    fp = c(("rejected_false_positive",))
    avoided = fixed * policy["manual_fix_minutes"] + fp * policy["manual_triage_minutes"]
    return {"alerts": len(results), "verified_fixes": fixed, "false_positives_screened": fp, "escalated_or_blocked": len(results) - fixed - fp,
            "machine_minutes": round(wall_seconds / 60, 2), "analyst_minutes_avoided_estimate": avoided,
            "assumptions": {"manual_fix_minutes": policy["manual_fix_minutes"], "manual_triage_minutes": policy["manual_triage_minutes"]}}


def write_report(out: Path, results, policy, wall_seconds, provider, audit_ok, tokens=0):
    m = roi(results, policy, wall_seconds)
    m["llm_tokens"] = tokens
    L = [f"# PatchSentinel run report", "", f"Provider: `{provider}` | Alerts: {m['alerts']} | Wall time: {m['machine_minutes']} min | {audit_ok}", "",
         "## Outcome", "", "| Alert | Function | Rule | Outcome | Attempts | Seconds |", "|---|---|---|---|---|---|"]
    for r in results:
        a = r["alert"]
        L.append(f"| {a['id']} | `{a['file']}:{a['function']}` | {a['rule_id']} | {LABELS.get(r['status'], r['status'])} | {r.get('attempt', 0)} | {r['seconds']} |")
    L += ["", "## Business value (estimate)", "",
          f"- Fixes proven by exploit test and reviewed: **{m['verified_fixes']}**; false positives screened before any patch: **{m['false_positives_screened']}**; escalated or blocked: **{m['escalated_or_blocked']}**.",
          f"- Machine time: **{m['machine_minutes']} min**; LLM tokens used: **{tokens}**. Estimated analyst time avoided: **{m['analyst_minutes_avoided_estimate']} min**, "
          f"computed as fixes x {policy['manual_fix_minutes']} min + false positives x {policy['manual_triage_minutes']} min.",
          "- The per-item minutes are **assumptions** set in `policy.json`, not measured results. Replace them with your team's own baseline.", "", "## Evidence per alert", ""]
    for r in results:
        a = r["alert"]
        L += [f"### {a['id']} `{a['function']}()` - {LABELS.get(r['status'], r['status'])}", f"Reason: {r.get('reason', '')}", ""]
        if r.get("checks"):
            L += ["| Check | Result | Detail |", "|---|---|---|"] + [f"| {k} | {'PASS' if v[0] else 'FAIL'} | {v[1][:120]} |" for k, v in r["checks"].items()] + [""]
        if r.get("diff"):
            L += ["```diff", r["diff"], "```", ""]
    (out / "report.md").write_text("\n".join(L), encoding="utf-8")
    (out / "results.json").write_text(json.dumps({"metrics": m, "results": [
        {k: v for k, v in r.items() if k not in ("new_source", "diff")} for r in results]}, indent=2, default=str), encoding="utf-8")
    return m
